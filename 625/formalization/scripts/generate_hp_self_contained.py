#!/usr/bin/env python3
"""Generate the project-self-contained Erdos625HP Lean proof file.

The output (`Erdos625HPSelfContained.lean`) contains the complete transitive
closure of the local modules imported by `Erdos625HP.lean` (across both
`Erdos625` and `Erdos625HP`), in dependency order, with all local `import`
commands stripped and only external Mathlib imports retained at the top.
`Erdos625SelfContained.lean` is left untouched.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path


PROJECT_DIR = Path(__file__).resolve().parents[1]
ROOT_MODULE = "Erdos625HP"
LOCAL_ROOTS = ("Erdos625", "Erdos625HP")
OUTPUT = PROJECT_DIR / "Erdos625HPSelfContained.lean"
IMPORT_RE = re.compile(r"^\s*import\s+(.+?)\s*$")


def normalized_text(path: Path) -> str:
    """Read UTF-8 source and normalize line endings for reproducible output."""
    return path.read_text(encoding="utf-8-sig").replace("\r\n", "\n").replace("\r", "\n")


def is_local_module(name: str) -> bool:
    return any(name == root or name.startswith(f"{root}.") for root in LOCAL_ROOTS)


def module_sources() -> dict[str, Path]:
    sources: dict[str, Path] = {}
    for root in LOCAL_ROOTS:
        sources[root] = PROJECT_DIR / f"{root}.lean"
        for path in sorted((PROJECT_DIR / root).rglob("*.lean")):
            relative = path.relative_to(PROJECT_DIR).with_suffix("")
            sources[".".join(relative.parts)] = path
    return sources


def imports_in(text: str, path: Path) -> list[str]:
    imports: list[str] = []
    for line_number, line in enumerate(text.splitlines(), start=1):
        match = IMPORT_RE.match(line)
        if match is None:
            continue
        command = match.group(1).split("--", maxsplit=1)[0].strip()
        names = command.split()
        if not names:
            raise ValueError(f"empty import command at {path}:{line_number}")
        imports.extend(names)
    return imports


def body_without_imports(text: str) -> str:
    lines = [line for line in text.splitlines() if IMPORT_RE.match(line) is None]
    return "\n".join(lines).strip("\n")


def closure_in_dependency_order(
    sources: dict[str, Path],
) -> tuple[list[str], list[str], dict[str, str]]:
    texts = {module: normalized_text(path) for module, path in sources.items()}
    dependencies = {
        module: imports_in(text, sources[module]) for module, text in texts.items()
    }
    ordered: list[str] = []
    external: set[str] = set()
    permanent: set[str] = set()
    temporary: list[str] = []

    def visit(module: str) -> None:
        if module in permanent:
            return
        if module in temporary:
            cycle = " -> ".join([*temporary, module])
            raise ValueError(f"cyclic local import graph: {cycle}")
        if module not in sources:
            raise ValueError(f"missing source for local module {module}")

        temporary.append(module)
        for dependency in dependencies[module]:
            if is_local_module(dependency):
                visit(dependency)
            else:
                external.add(dependency)
        temporary.pop()
        permanent.add(module)
        ordered.append(module)

    visit(ROOT_MODULE)
    return ordered, sorted(external), texts


def section_name(module: str) -> str:
    safe = re.sub(r"[^A-Za-z0-9_]", "_", module)
    return f"Erdos625HPSelfContained_Module_{safe}"


